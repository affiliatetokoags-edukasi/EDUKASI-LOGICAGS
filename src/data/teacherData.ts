// Helper to determine tier
export function getStudentTier(mastery: number, notStarted: boolean = false) {
  if (notStarted || mastery === 0) return 'not_started';
  if (mastery >= 90) return 'master';
  if (mastery >= 80) return 'advanced';
  if (mastery >= 70) return 'capable';
  if (mastery >= 60) return 'developing';
  return 'needs_practice';
}

